#!/usr/bin/env bash
# Verify one wave. All dependent work stops after a failed prerequisite.
source "$(dirname "$0")/env.sh"
set +e
here="$(cd "$(dirname "$0")" && pwd)"
label="${1:-adhoc}"
[[ "$label" =~ ^[A-Za-z0-9][A-Za-z0-9._-]*$ ]] || { echo "invalid verification label" >&2; exit 2; }
report="$CLIENT240_DOCS/verification/$label.md"
mkdir -p "$CLIENT240_CACHE" "$CLIENT240_DOCS/verification"
status=0
body=""
section() { body+=$'\n'"## $1"$'\n\n```text\n'"$2"$'\n```\n'; }
check() {
  local title="$1" out rc
  shift
  out="$("$@" 2>&1)"; rc=$?
  if [[ $rc -ne 0 ]]; then status=1; title="$title: FAILED"; else title="$title: ok"; fi
  section "$title" "$out"
  return "$rc"
}
finish() {
  {
    echo "# Verification: $label"
    echo
    echo "Generated by \`tools/client-240/verify.sh\`. Result: $([[ $status -eq 0 ]] && echo PASS || echo FAIL)."
    echo "Hand review of T3/T4 entries is separate. A failed prerequisite leaves dependent checks NOT RUN."
    printf '%s' "$body"
  } > "$report"
  echo "wrote ${report#$CLIENT240_REPO/}: $([[ $status -eq 0 ]] && echo PASS || echo FAIL)"
  exit "$status"
}
annotations_identical() {
  client240_tool annotations "$CLIENT240_SEMANTIC_JAR" > "$CLIENT240_CACHE/annotations-base-unsorted.txt" || return 1
  client240_tool annotations "$CLIENT240_CACHE/readable.jar" > "$CLIENT240_CACHE/annotations-readable-unsorted.txt" || return 1
  sort "$CLIENT240_CACHE/annotations-base-unsorted.txt" > "$CLIENT240_CACHE/annotations-base.txt" || return 1
  sort "$CLIENT240_CACHE/annotations-readable-unsorted.txt" > "$CLIENT240_CACHE/annotations-readable.txt" || return 1
  local lines
  lines="$(wc -l < "$CLIENT240_CACHE/annotations-base.txt" | tr -d ' ')"
  [[ "$lines" -gt 0 ]] || { echo "empty annotation evidence"; return 1; }
  diff "$CLIENT240_CACHE/annotations-base.txt" "$CLIENT240_CACHE/annotations-readable.txt" && echo "$lines annotation lines identical"
}
references_untouched() {
  local dirty
  dirty="$(git -C "$CLIENT240_REPO" status --porcelain -- references)" || return 1
  [[ -z "$dirty" ]] || { echo "$dirty"; return 1; }
  echo "no changes under references/"
}
decompile_report() {
  "$here/decompile.sh" "$CLIENT240_CACHE/readable.jar" "$CLIENT240_CACHE/readable-src" || return 1
  python3 - "$CLIENT240_CACHE/readable-src" <<'PY'
from pathlib import Path
import sys
sources = list(Path(sys.argv[1]).rglob('*.java'))
failures = [p.name for p in sources if "Couldn't be decompiled" in p.read_text(errors='replace')]
print(f'source files: {len(sources)}; expected: 735; failed bodies: {len(failures)}')
for name in failures: print(name)
raise SystemExit(bool(failures) or len(sources) != 735)
PY
}
shards=("$CLIENT240_DOCS"/mappings/clusters/*.tiny)
check "Pinned tools, inputs and JDK" client240_require_inputs || finish
check "Mapping shards valid, current and collision free" client240_tool validate "$CLIENT240_SEMANTIC_JAR" "${shards[@]}" || finish
check "Ledger and mapping agree" python3 "$here/ledger_check.py" "$CLIENT240_DOCS" || finish
check "Merge mappings" "$here/merge-mappings.sh" || finish
check "Merged mapping valid" client240_tool validate "$CLIENT240_SEMANTIC_JAR" "$CLIENT240_DOCS/mappings/merged.tiny" || finish
check "Generate ledger" python3 "$here/ledger_check.py" "$CLIENT240_DOCS" --write || finish
rm -f "$CLIENT240_CACHE/readable.jar" "$CLIENT240_CACHE/roundtrip.jar"
check "Forward remap" "$here/remap.sh" forward "$CLIENT240_CACHE/readable.jar" || finish
check "Round-trip remap" "$here/remap.sh" roundtrip "$CLIENT240_CACHE/roundtrip.jar" || finish
check "Rename-only proof" client240_tool compare "$CLIENT240_SEMANTIC_JAR" "$CLIENT240_CACHE/roundtrip.jar" || finish
check "Obfuscated-name/signature evidence identical" annotations_identical || finish
check "Readable sources regenerate" decompile_report || finish
check "References untouched" references_untouched || finish
check "Coverage of generic names" python3 "$here/coverage.py" "$CLIENT240_REPO/references/rl-suite-240/sources-semantic" "$CLIENT240_DOCS/mappings/merged.tiny"
finish
