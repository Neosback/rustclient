#!/usr/bin/env bash
# verify.sh [WAVE_LABEL] : run every wave check and write verification/<label>.md.
# Exit status is non-zero when any check fails. Generated artifacts stay under .cache/client-240.
source "$(dirname "$0")/env.sh"
set +e
here="$(cd "$(dirname "$0")" && pwd)"
label="${1:-adhoc}"
report="$CLIENT240_DOCS/verification/$label.md"
mkdir -p "$CLIENT240_CACHE" "$CLIENT240_DOCS/verification"
status=0
body=""

section() { body+=$'\n'"## $1"$'\n\n```text\n'"$2"$'\n```\n'; }
check() { # check TITLE COMMAND... : run in this shell so shell functions are visible
  local title="$1" out rc
  shift
  out="$("$@" 2>&1)"
  rc=$?
  if [[ $rc -ne 0 ]]; then status=1; title="$title: FAILED"; else title="$title: ok"; fi
  section "$title" "$out"
}

pinned() { echo "original gamepack $CLIENT240_INPUT_SHA"; echo "semantic jar     $CLIENT240_SEMANTIC_SHA"; }

annotations_identical() {
  client240_tool annotations "$CLIENT240_SEMANTIC_JAR" | sort > "$CLIENT240_CACHE/annotations-base.txt"
  client240_tool annotations "$CLIENT240_CACHE/readable.jar" | sort > "$CLIENT240_CACHE/annotations-readable.txt"
  local lines
  lines="$(wc -l < "$CLIENT240_CACHE/annotations-base.txt" | tr -d ' ')"
  if [[ "$lines" -eq 0 ]]; then echo "no annotation lines found; the check proved nothing"; return 1; fi
  diff "$CLIENT240_CACHE/annotations-base.txt" "$CLIENT240_CACHE/annotations-readable.txt" && echo "$lines annotation lines identical"
}

references_untouched() {
  local dirty
  dirty="$(git -C "$CLIENT240_REPO" status --porcelain -- references)"
  if [[ -n "$dirty" ]]; then echo "$dirty"; return 1; fi
  echo "no changes under references/"
}

decompile_report() {
  "$here/decompile.sh" "$CLIENT240_CACHE/readable.jar" "$CLIENT240_CACHE/readable-src" || return 1
  local failures baseline
  failures="$(grep -rl "Couldn't be decompiled" "$CLIENT240_CACHE/readable-src" 2>/dev/null | wc -l | tr -d ' ')"
  baseline="$(grep -rl "Couldn't be decompiled" "$CLIENT240_REPO/references/rl-suite-240/sources-semantic" 2>/dev/null | wc -l | tr -d ' ')"
  echo "files with decompile failures: $failures (pinned rl-suite sources: $baseline)"
  echo "informational only: the pinned sources came from a different decompiler configuration"
}

client240_require_inputs || { echo "input verification failed" >&2; exit 1; }
"$here/merge-mappings.sh" > /dev/null

shards=("$CLIENT240_DOCS"/mappings/clusters/*.tiny)
check "Inputs pinned" pinned
check "Mapping shards valid, current and collision free" client240_tool validate "$CLIENT240_SEMANTIC_JAR" "${shards[@]}"
check "Ledger and mapping agree" python3 "$here/ledger_check.py" "$CLIENT240_DOCS" --write

rm -f "$CLIENT240_CACHE/readable.jar" "$CLIENT240_CACHE/roundtrip.jar"
check "Forward remap" "$here/remap.sh" forward "$CLIENT240_CACHE/readable.jar"
check "Round-trip remap" "$here/remap.sh" roundtrip "$CLIENT240_CACHE/roundtrip.jar"
if [[ -f "$CLIENT240_CACHE/readable.jar" && -f "$CLIENT240_CACHE/roundtrip.jar" ]]; then
  check "Rename-only proof (mapping then inverse equals the semantic jar)" \
    client240_tool compare "$CLIENT240_SEMANTIC_JAR" "$CLIENT240_CACHE/roundtrip.jar"
  check "Obfuscated-name and signature evidence identical" annotations_identical
  check "Readable sources regenerate" decompile_report
fi
check "References untouched" references_untouched
check "Coverage of generic names" python3 "$here/coverage.py" \
  "$CLIENT240_REPO/references/rl-suite-240/sources-semantic" "$CLIENT240_DOCS/mappings/merged.tiny"

{
  echo "# Verification: $label"
  echo
  echo "Generated by \`tools/client-240/verify.sh\`. Result: $([[ $status -eq 0 ]] && echo PASS || echo FAIL)."
  echo "Hand review of T3/T4 entries is separate and is recorded in the cluster write-up."
  printf '%s' "$body"
} > "$report"
echo "wrote ${report#$CLIENT240_REPO/}: $([[ $status -eq 0 ]] && echo PASS || echo FAIL)"
exit $status
