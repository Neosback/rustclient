#!/usr/bin/env python3
"""Generate the interface-styles sprite table from the vendored RuneLite sources.

`SpriteOverride` is an enum of `NAME(SpriteID.Group.CONSTANT, SKIN, SKIN...)` rows; the plugin loads
`<skin>/<spriteId>.png` for each row whose skin list contains the configured skin (a skin that extends
another reads that skin's directory). This resolves every row against `gameval/SpriteID.java`, copies
the PNG files it needs into `crates/first-party-plugins/assets/interfacestyles/` and writes
`crates/first-party-plugins/src/interfacestyles_sprites.rs` with one `include_bytes!` entry per
(skin, sprite) pair. All inputs are read-only under `references/`.
"""
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / "references/open-runelite-rev-240"
PLUGIN = REF / "runelite-client/src/main/java/net/runelite/client/plugins/interfacestyles"
RESOURCES = REF / "runelite-client/src/main/resources/net/runelite/client/plugins/interfacestyles"
SPRITE_ID = REF / "runelite-api/src/main/java/net/runelite/api/gameval/SpriteID.java"
ASSETS = ROOT / "crates/first-party-plugins/assets/interfacestyles"
OUT = ROOT / "crates/first-party-plugins/src/interfacestyles_sprites.rs"

# `Skin.toString()` names: the directory a skin reads, and the extended skin if any.
DIRECTORY = {"AROUND_2005": "2005", "AROUND_2006": "2005", "AROUND_2010": "2010"}


def sprite_constants():
    """`Group.CONSTANT` (or a bare `CONSTANT`) -> id, following the nested classes."""
    values = {}
    stack = []
    for line in SPRITE_ID.read_text().splitlines():
        line = line.strip()
        match = re.match(r"public static final class (\w+)", line)
        if match:
            stack.append(match.group(1))
            continue
        if line == "}" and stack:
            stack.pop()
            continue
        match = re.match(r"public static final int (\w+) = (-?\d+|\w+);", line)
        if match:
            prefix = ".".join(stack)
            raw = match.group(2)
            # Aliases (`COMBAT = _0;`) refer to a constant of the same class.
            value = int(raw) if re.fullmatch(r"-?\d+", raw) else values[f"{prefix}.{raw}" if prefix else raw]
            values[f"{prefix}.{match.group(1)}" if prefix else match.group(1)] = value
    return values


def main():
    constants = sprite_constants()
    source = (PLUGIN / "SpriteOverride.java").read_text()
    # Drop commented-out rows.
    source = re.sub(r"^\s*//.*$", "", source, flags=re.M)
    rows = re.findall(r"^\s*\w+\(SpriteID\.([\w.]+),\s*([\w, ]+)\)[,;]", source, flags=re.M)
    entries = {}
    missing = []
    for name, skins in rows:
        if name not in constants:
            missing.append(name)
            continue
        sprite = constants[name]
        for skin in (s.strip() for s in skins.split(",")):
            directory = DIRECTORY[skin]
            png = RESOURCES / directory / f"{sprite}.png"
            if not png.exists():
                missing.append(f"{directory}/{sprite}.png")
                continue
            entries[(skin, sprite)] = directory
    if missing:
        print("unresolved:", ", ".join(missing), file=sys.stderr)
        return 1
    if ASSETS.exists():
        shutil.rmtree(ASSETS)
    lines = []
    for (skin, sprite), directory in sorted(entries.items()):
        target = ASSETS / directory / f"{sprite}.png"
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(RESOURCES / directory / f"{sprite}.png", target)
        lines.append(
            f"    Entry {{ skin: Skin::{ {'AROUND_2005':'Around2005','AROUND_2006':'Around2006','AROUND_2010':'Around2010'}[skin] }, "
            f"sprite: {sprite}, png: include_bytes!(\"../assets/interfacestyles/{directory}/{sprite}.png\") }},\n"
        )
    OUT.write_text(
        "// Generated by tools/builtin-plugins/interfacestyles_sprites.py from\n"
        "// InterfaceStylesPlugin/SpriteOverride, gameval/SpriteID and the plugin's resource PNGs\n"
        "// (RuneLite, BSD-2; see NOTICE). Do not edit by hand.\n\n"
        "use crate::interfacestyles::{Entry, Skin};\n\n"
        "/// Every (skin, sprite) replacement, sorted by skin then sprite id.\n"
        f"pub(crate) const SPRITES: [Entry; {len(lines)}] = [\n{''.join(lines)}];\n"
    )
    print(f"{len(rows)} rows, {len(lines)} (skin, sprite) entries -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
