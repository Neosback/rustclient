#!/usr/bin/env python3
"""Generate the idle-notifier animation table from the vendored RuneLite sources.

`IdleNotifierPlugin.onAnimationChanged` is a `switch` over `AnimationID` constants. This reads the
case labels of the animation switch and resolves each against `net.runelite.api.gameval.AnimationID`
(both read-only under `references/`), then writes a sorted `const` table to
`crates/first-party-plugins/src/idlenotifier_animations.rs`.

Only the labels before `case AnimationID.LUNAR_HUMAN_MAGIC_SUMMON2` are the plain "start a skilling
action" ids; the summon and `-1` cases keep their own logic in the plugin.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
API = ROOT / "references/open-runelite-rev-240/runelite-api/src/main/java/net/runelite/api/gameval"
PLUGIN = (
    ROOT
    / "references/open-runelite-rev-240/runelite-client/src/main/java/net/runelite/client/plugins/idlenotifier/IdleNotifierPlugin.java"
)
OUT = ROOT / "crates/first-party-plugins/src/idlenotifier_animations.rs"


def main():
    plugin = PLUGIN.read_text()
    start = plugin.index("switch (animation)")
    end = plugin.index("case AnimationID.LUNAR_HUMAN_MAGIC_SUMMON2:", start)
    names = re.findall(r"case AnimationID\.(\w+):", plugin[start:end])
    values = {
        name: int(value)
        for name, value in re.findall(
            r"public static final int (\w+) = (-?\d+);", (API / "AnimationID.java").read_text()
        )
    }
    missing = [name for name in names if name not in values]
    if missing:
        print("unresolved AnimationID constants:", ", ".join(missing), file=sys.stderr)
        return 1
    ids = sorted({values[name] for name in names})
    rows = "".join(f"    {value},\n" for value in ids)
    OUT.write_text(
        "// Generated by tools/builtin-plugins/idlenotifier_animations.py from\n"
        "// IdleNotifierPlugin.onAnimationChanged and gameval/AnimationID (RuneLite, BSD-2; see NOTICE).\n"
        "// Do not edit by hand.\n\n"
        "/// Animations that restart the idle-animation timer, ascending.\n"
        f"pub(crate) const SKILLING_ANIMATIONS: [u32; {len(ids)}] = [\n{rows}];\n"
    )
    print(f"{len(names)} labels, {len(ids)} distinct ids -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
