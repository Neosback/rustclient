//! Typed first-party configuration. The external component 0.1 ABI is unchanged.
use rustclient_plugin_api::PluginId;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;

/// Keyboard binding in platform-neutral key names; modifiers: Shift/Control/Alt/Meta bits.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Hotkey {
    pub key: String,
    pub modifiers: u8,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Font {
    pub family: String,
    pub size: u16,
    pub bold: bool,
    pub italic: bool,
}

/// One validated configuration value, independent of any GUI or GPU representation.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "type", content = "value", rename_all = "snake_case")]
pub enum ConfigValue {
    Boolean(bool),
    Integer(i32),
    Choice(String),
    Color(u32),
    Hotkey(Hotkey),
    Size([u32; 2]),
    Font(Font),
}

/// Controls generated by shell-ui from the same schema used for validation.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Control {
    Boolean,
    Integer { min: i32, max: i32 },
    Choice { options: Vec<String> },
    Color,
    Hotkey,
    Size,
    Font,
}

/// Source-backed descriptor of one configuration option.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct Setting {
    pub key: String,
    pub label: String,
    pub description: String,
    pub section: String,
    pub control: Control,
    pub default: ConfigValue,
    pub source: String,
}
impl Setting {
    /// Validate the actual value, rather than relying on a widget's bounds.
    #[must_use]
    pub fn accepts(&self, value: &ConfigValue) -> bool {
        match (&self.control, value) {
            (Control::Boolean, ConfigValue::Boolean(_))
            | (Control::Color, ConfigValue::Color(_)) => true,
            (Control::Integer { min, max }, ConfigValue::Integer(n)) => (min..=max).contains(&n),
            (Control::Choice { options }, ConfigValue::Choice(value)) => options.contains(value),
            (Control::Hotkey, ConfigValue::Hotkey(key)) => {
                key.modifiers < 16
                    && key.key.len() <= 32
                    && key.key.bytes().all(|c| c.is_ascii_alphanumeric())
            }
            (Control::Size, ConfigValue::Size([width, height])) => {
                (320..=16384).contains(width) && (200..=16384).contains(height)
            }
            (Control::Font, ConfigValue::Font(font)) => {
                !font.family.is_empty()
                    && font.family.len() <= 128
                    && !font.family.chars().any(char::is_control)
                    && (6..=96).contains(&font.size)
            }
            _ => false,
        }
    }
}

/// Immutable configuration schema for one application service.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct ConfigSchema {
    pub plugin: PluginId,
    pub name: String,
    pub version: u32,
    pub settings: Vec<Setting>,
}

/// Accepted values only; missing entries use schema defaults.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ConfigDocument {
    pub version: u32,
    pub values: BTreeMap<String, ConfigValue>,
}

/// Emitted only after the owner has applied and persisted an accepted candidate.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ConfigChanged {
    pub plugin: PluginId,
    pub generation: u64,
    pub previous: ConfigDocument,
    pub current: ConfigDocument,
}

/// One owner of the accepted application preferences for a service.
pub struct Configuration {
    schema: ConfigSchema,
    document: ConfigDocument,
    generation: u64,
}
impl Configuration {
    /// Reject invalid schemas and corrupt/incompatible stored data without accepting partial values.
    /// # Errors
    /// Includes the offending schema/key; never silently discards unknown saved options.
    pub fn new(schema: ConfigSchema, stored: Option<&[u8]>) -> Result<Self, String> {
        let mut keys = std::collections::BTreeSet::new();
        if schema.version == 0
            || schema.settings.iter().any(|setting| {
                setting.key.is_empty()
                    || !keys.insert(&setting.key)
                    || !setting.accepts(&setting.default)
            })
        {
            return Err(format!("{}: invalid configuration schema", schema.plugin));
        }
        let document = if let Some(bytes) = stored {
            serde_json::from_slice(bytes)
                .map_err(|error| format!("{}: stored configuration: {error}", schema.plugin))?
        } else {
            ConfigDocument {
                version: schema.version,
                values: BTreeMap::new(),
            }
        };
        Self::validate(&schema, &document)?;
        Ok(Self {
            schema,
            document,
            generation: 0,
        })
    }

    fn validate(schema: &ConfigSchema, document: &ConfigDocument) -> Result<(), String> {
        if document.version != schema.version {
            return Err(format!("{}: configuration version", schema.plugin));
        }
        for (key, value) in &document.values {
            let setting = schema
                .settings
                .iter()
                .find(|setting| setting.key == *key)
                .ok_or_else(|| format!("{}: unknown setting {key}", schema.plugin))?;
            if !setting.accepts(value) {
                return Err(format!("{}: invalid value for {key}", schema.plugin));
            }
        }
        Ok(())
    }

    #[must_use]
    pub fn schema(&self) -> &ConfigSchema {
        &self.schema
    }
    #[must_use]
    pub fn generation(&self) -> u64 {
        self.generation
    }
    #[must_use]
    pub fn document(&self) -> &ConfigDocument {
        &self.document
    }
    #[must_use]
    pub fn value(&self, key: &str) -> Option<&ConfigValue> {
        self.document.values.get(key).or_else(|| {
            self.schema
                .settings
                .iter()
                .find(|setting| setting.key == key)
                .map(|setting| &setting.default)
        })
    }

    /// Apply/persist a validated candidate through its owning service before publishing it.
    /// The transaction must preserve its previous effect and persistent document on error.
    /// # Errors
    /// Invalid values, exhausted generations or owner transaction failures leave this owner unchanged.
    pub fn change(
        &mut self,
        key: &str,
        value: ConfigValue,
        transaction: impl FnOnce(&ConfigDocument, &ConfigDocument) -> Result<(), String>,
    ) -> Result<Option<ConfigChanged>, String> {
        let mut candidate = self.document.clone();
        candidate.values.insert(key.to_owned(), value);
        self.replace(candidate, transaction)
    }

    /// Reset every setting in one transaction.
    /// # Errors
    /// Transaction failures retain the previous accepted values.
    pub fn reset(
        &mut self,
        transaction: impl FnOnce(&ConfigDocument, &ConfigDocument) -> Result<(), String>,
    ) -> Result<Option<ConfigChanged>, String> {
        self.replace(
            ConfigDocument {
                version: self.schema.version,
                values: BTreeMap::new(),
            },
            transaction,
        )
    }

    fn replace(
        &mut self,
        candidate: ConfigDocument,
        transaction: impl FnOnce(&ConfigDocument, &ConfigDocument) -> Result<(), String>,
    ) -> Result<Option<ConfigChanged>, String> {
        Self::validate(&self.schema, &candidate)?;
        if self.schema.settings.iter().all(|setting| {
            candidate
                .values
                .get(&setting.key)
                .unwrap_or(&setting.default)
                == self.value(&setting.key).unwrap_or(&setting.default)
        }) {
            return Ok(None);
        }
        let generation = self
            .generation
            .checked_add(1)
            .ok_or("configuration generation exhausted")?;
        transaction(&self.document, &candidate)?;
        let previous = std::mem::replace(&mut self.document, candidate);
        self.generation = generation;
        Ok(Some(ConfigChanged {
            plugin: self.schema.plugin.clone(),
            generation,
            previous,
            current: self.document.clone(),
        }))
    }
}
